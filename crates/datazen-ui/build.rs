//! Generates the zh-CN translation table from the React locale packs.
//!
//! The React frontend is the single source of truth for translated strings:
//! `packages/frontend/src/locales/zh-CN/*.ts`. Copying those strings by hand
//! would drift, and committing the generated table would hide the drift, so the
//! table is rebuilt into `OUT_DIR` whenever a locale pack changes.
//!
//! Only the value side of each `'key': 'value'` pair is read; the packs are
//! plain object literals with no interpolation of their own (placeholders such
//! as `{count}` stay in the string and are substituted by the caller).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let locales = manifest.join("../../packages/frontend/src/locales/zh-CN");
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("out dir"));

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", locales.display());

    let mut table = BTreeMap::new();
    let mut packs = match std::fs::read_dir(&locales) {
        Ok(entries) => entries
            .filter_map(|entry| entry.ok().map(|entry| entry.path()))
            .filter(|path| path.extension().is_some_and(|ext| ext == "ts"))
            .filter(|path| path.file_name().is_some_and(|name| name != "index.ts"))
            .collect::<Vec<_>>(),
        Err(error) => {
            panic!("cannot read {}: {error}", locales.display());
        }
    };
    packs.sort();

    for pack in &packs {
        println!("cargo:rerun-if-changed={}", pack.display());
        let source = std::fs::read_to_string(pack)
            .unwrap_or_else(|error| panic!("cannot read {}: {error}", pack.display()));
        for (key, value) in parse_pairs(&strip_comments(&source)) {
            table.insert(key, value);
        }
    }

    assert!(
        !table.is_empty(),
        "no zh-CN entries found under {}",
        locales.display()
    );

    let mut generated = String::from("// Generated by crates/datazen-ui/build.rs from the zh-CN locale packs.\n");
    let _ = writeln!(generated, "pub(crate) static ZH_CN: [(&str, &str); {}] = [", table.len());
    for (key, value) in &table {
        let _ = writeln!(generated, "    ({}, {}),", rust_string(key), rust_string(value));
    }
    generated.push_str("];\n");

    let target = out.join("i18n_zh.rs");
    std::fs::write(&target, generated)
        .unwrap_or_else(|error| panic!("cannot write {}: {error}", target.display()));
}

/// Drops `//` and `/* */` comments while leaving string literals untouched.
///
/// The packs are annotated with prose comments (`// DBR-04: the panel's mode
/// row`), and an apostrophe in one of those would otherwise start a bogus
/// literal and swallow the entries after it.
fn strip_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut chars = source.chars().peekable();
    let mut quote: Option<char> = None;
    while let Some(ch) = chars.next() {
        match quote {
            Some(open) => {
                out.push(ch);
                if ch == '\\' {
                    if let Some(next) = chars.next() {
                        out.push(next);
                    }
                } else if ch == open {
                    quote = None;
                }
            }
            None => {
                if ch == '/' && chars.peek() == Some(&'/') {
                    for next in chars.by_ref() {
                        if next == '\n' {
                            out.push('\n');
                            break;
                        }
                    }
                    continue;
                }
                if ch == '/' && chars.peek() == Some(&'*') {
                    chars.next();
                    let mut previous = '\0';
                    for next in chars.by_ref() {
                        if previous == '*' && next == '/' {
                            break;
                        }
                        previous = next;
                    }
                    continue;
                }
                if ch == '\'' || ch == '"' {
                    quote = Some(ch);
                }
                out.push(ch);
            }
        }
    }
    out
}

/// Every `'key': 'value'` pair in `source`, unescaped.
///
/// Keys and values may be single- or double-quoted, and a value may start on the
/// line after its key. Comments and any other text are skipped.
fn parse_pairs(source: &str) -> Vec<(String, String)> {
    let bytes = source.as_bytes();
    let mut pairs = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] != b'\'' && bytes[i] != b'"' {
            i += 1;
            continue;
        }
        let quote = bytes[i];
        let Some((key, after_key)) = read_quoted(bytes, i) else {
            i += 1;
            continue;
        };
        let mut j = after_key;
        while j < bytes.len() && bytes[j].is_ascii_whitespace() {
            j += 1;
        }
        if j >= bytes.len() || bytes[j] != b':' {
            i = after_key;
            continue;
        }
        j += 1;
        while j < bytes.len() && bytes[j].is_ascii_whitespace() {
            j += 1;
        }
        let Some((value, after_value)) = read_quoted(bytes, j) else {
            i = after_key;
            continue;
        };
        if is_translation_key(&key) {
            pairs.push((key, value));
        }
        i = after_value.max(after_key).max(i + 1);
        let _ = quote;
    }
    pairs
}

/// Reads the quoted run starting at `start`, returning the unescaped text and
/// the index just past the closing quote.
fn read_quoted(bytes: &[u8], start: usize) -> Option<(String, usize)> {
    let quote = *bytes.get(start)?;
    if quote != b'\'' && quote != b'"' {
        return None;
    }
    let mut text = String::new();
    let mut i = start + 1;
    while i < bytes.len() {
        let ch = bytes[i];
        if ch == b'\\' {
            let escaped = *bytes.get(i + 1)?;
            match escaped {
                b'n' => text.push('\n'),
                b't' => text.push('\t'),
                b'r' => text.push('\r'),
                other => text.push(other as char),
            }
            i += 2;
            continue;
        }
        if ch == quote {
            return Some((text, i + 1));
        }
        // Copy UTF-8 runs verbatim: the packs are mostly Chinese text.
        let rest = std::str::from_utf8(&bytes[i..]).ok()?;
        let scalar = rest.chars().next()?;
        text.push(scalar);
        i += scalar.len_utf8();
    }
    None
}

/// A dotted key such as `common.save`; anything else (`index.ts` imports, prose)
/// is not a dictionary entry.
fn is_translation_key(key: &str) -> bool {
    !key.is_empty()
        && key.contains('.')
        && !key.starts_with('.')
        && key
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '.' | '_' | '-'))
}

fn rust_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}
