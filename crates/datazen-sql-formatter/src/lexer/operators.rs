//! Longest alternatives in the pinned dialect operator group.
use crate::Dialect;

pub(super) fn operators(dialect: Dialect) -> &'static [&'static str] {
    match dialect {
        Dialect::Sql => &[
            "<>", "<=", ">=", "!=", "||", "+", "-", "/", ">", "<", "=",
        ],
        Dialect::Sqlite => &[
            "->>", "<>", "<=", ">=", "!=", "<<", ">>", "==", "->", "||", "+",
            "-", "/", ">", "<", "=", "%", "~", "&", "|",
        ],
        Dialect::PostgreSql => &[
            "<<<->", "<->>>", "~>=~", "~<=~", "!~~*", "<<->", "<->>", "||/", "~>~", "~<~", "@-@",
            "<->", "<<|", "&<|", "|>>", "|&>", "?-|", "?||", "<@>", "->>", "#>>", ">>=",
            "<<=", "~~*", "!~~", "!~*", "-|-", "@@@", "<<%", "%>>", "<#>", "<=>", "<+>",
            "<~>", "<%>", "&&&", "|=|", "<>", "<=", ">=", "!=", "|/", ":=", "<<",
            ">>", "@@", "##", "&&", "&<", "&>", "<^", ">^", "?#", "?-", "?|",
            "@>", "<@", "~=", "@?", "?&", "->", "#>", "#-", "=>", "~~", "~*",
            "!~", "||", "!!", "^@", "<%", "%>", "~>", "#=", "::", "+", "-",
            "/", ">", "<", "=", "%", "^", "@", "&", "|", "#", "~",
            "?", ":",
        ],
        Dialect::MySql => &[
            "<=>", "->>", "*.*", "<>", "<=", ">=", "!=", ":=", "<<", ">>", "->",
            "&&", "||", "+", "-", "/", ">", "<", "=", "%", "&", "|",
            "^", "~", "!",
        ],
        Dialect::MariaDb => &[
            "<=>", "*.*", "<>", "<=", ">=", "!=", ":=", "<<", ">>", "&&", "||",
            "+", "-", "/", ">", "<", "=", "%", "&", "|", "^", "~",
            "!",
        ],
        Dialect::TransactSql => &[
            "<>", "<=", ">=", "!=", "!<", "!>", "+=", "-=", "*=", "/=", "%=",
            "|=", "&=", "^=", "::", "+", "-", "/", ">", "<", "=", "%",
            "&", "|", "^", "~", ":",
        ],
    }
}
