//! Original v15.8.2 disambiguated tokens and output, generated offline from
//! pinned tokenizer/formatter on synthetic non-production SQL. Exercises
//! layout independently; the host tests additionally exercise the Rust lexer.
use super::*;
use std::time::Duration;

fn t<'a>(kind: Kind, text: &'a str, whitespace_before: &'a str, offset: usize) -> Token<'a> {
    Token { text, whitespace_before, offset, kind }
}

fn check_layout(id: &str, tokens: &[Token<'_>], options: Options, expected: &str) {
    let actual = format_tokens(tokens, &options, 1024 * 1024, Instant::now() + Duration::from_secs(3));
    assert_eq!(actual.as_deref(), Ok(expected), "{id}");
}

