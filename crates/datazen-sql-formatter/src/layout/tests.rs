#[test]
fn unsupported_fail_closed_and_limits_apply_to_layout_itself() {
    let mut opts = Options {
        dialect: Dialect::Sqlite,
        keyword_case: KeywordCase::Upper,
        indent: Indent::Spaces(2),
        logical_operator_newline: LogicalOperatorNewline::Before,
        lines_between_queries: 1,
    };
    let select = t(Kind::Keyword(Kw::Select), "select", "", 0);
    let from = t(Kind::Keyword(Kw::Clause), "from", " ", 9);
    let number = t(Kind::Number, "1", " ", 7);
    let comma = t(Kind::Punctuation, ",", "", 8);
    let plus = t(Kind::Operator, "+", "", 8);
    let insert = t(Kind::Keyword(Kw::Clause), "insert into", "", 0);
    let name = t(Kind::Word, "t", " ", 12);
    for tokens in [&[insert, name][..], &[select, number, comma, comma, number],
                   &[select, number, plus, from, name], &[select, number, from]] {
        assert!(matches!(format_tokens(tokens, &opts, 1024, Instant::now() + Duration::from_secs(3)),
            Err(Error::Unsupported)));
    }
    let tokens = [select, number];
    assert!(matches!(format_tokens(&tokens, &opts, 1, Instant::now() + Duration::from_secs(3)),
        Err(Error::OutputLimit)));
    assert!(matches!(format_tokens(&tokens, &opts, 128, Instant::now()), Err(Error::Deadline)));
    opts.dialect = Dialect::PostgreSql;
    assert!(matches!(format_tokens(&tokens, &opts, 1024, Instant::now() + Duration::from_secs(3)),
        Err(Error::Unsupported)));
}
