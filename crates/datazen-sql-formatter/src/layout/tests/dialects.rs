//! Pinned original v15.8.2 formatter and tokenizer, executed only to
//! produce these offline development expectations. These private grammar
//! tests never turn on the additional production dialects.
use super::*;

fn options(dialect: Dialect, keyword_case: KeywordCase, width: u8) -> Options {
    Options {
        dialect,
        keyword_case,
        indent: Indent::Spaces(width),
        logical_operator_newline: LogicalOperatorNewline::Before,
        lines_between_queries: 1,
    }
}

fn check(id: &str, input: &[Token<'_>], options: Options, expected: Result<&str, Error>) {
    let deadline = Instant::now() + Duration::from_secs(3);
    assert_eq!(format_admitted_tokens(input, &options, 1024 * 1024, deadline).as_deref(), expected.as_deref(), "{id}");
    assert_eq!(format_tokens(input, &options, 1024 * 1024, deadline).as_deref(), expected.as_deref(), "public route: {id}");
}

