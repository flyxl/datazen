use super::Fixture;
use datazen_driver_api::{DatabaseDriver, DriverError};
use datazen_driver_postgres::PostgresDriver;
use sqlx::PgConnection;
use std::sync::Arc;
use std::time::Duration;

#[tokio::test]
async fn identity_import_uses_server_ownership_bounds_and_no_destructive_fallback() {
    let mut fixture = Fixture::open().await;
    let suffix = uuid::Uuid::new_v4().simple().to_string();
    let schema = format!("dz_ids_{suffix}");
    let role = format!("dz_role_{suffix}");
    let config = fixture.config.clone();
    let driver = PostgresDriver::new();
    let handle = driver
        .connect_fixed_session(&config)
        .await
        .expect("independent import handle");
    sqlx::raw_sql(&format!(r#"
        CREATE SCHEMA {schema};
        CREATE ROLE {role} NOLOGIN;
        CREATE TABLE {schema}.bounds (id smallint GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 3 MAXVALUE 20) PRIMARY KEY);
        CREATE TABLE {schema}.roles (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
        CREATE TABLE {schema}.not_sequence (id integer PRIMARY KEY);
        GRANT USAGE ON SCHEMA {schema} TO {role};
        GRANT ALL PRIVILEGES ON TABLE {schema}.roles TO {role};
    "#))
    .execute(&mut fixture.oracle).await.expect("disposable ownership fixtures");
    driver
        .execute(&handle, &format!("SET search_path TO {schema}, pg_catalog"))
        .await
        .expect("unqualified table path fixture");
    let ids = ["id".into()];
    assert!(matches!(
        driver
            .advance_transfer_identity_sequences(&handle, None, "bounds", &ids)
            .await,
        Err(DriverError::TransactionError(_))
    ));
    driver
        .advance_transfer_identity_sequences(&handle, None, "bounds", &[])
        .await
        .expect("no work without columns");
    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("empty table transaction");
    driver
        .advance_transfer_identity_sequences(&handle, None, "bounds", &ids)
        .await
        .expect("empty sequence keeps nominal start");
    driver
        .commit(tx)
        .await
        .expect("commit without inserted values");
    let (next, called): (i64, bool) = sqlx::query_as(&format!(
        "SELECT last_value,is_called FROM {schema}.bounds_id_seq"
    ))
    .fetch_one(&mut fixture.oracle)
    .await
    .expect("reseed oracle");
    assert_eq!((next, called), (10, false));

    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("bounds transaction");
    driver
        .execute(&handle, "INSERT INTO bounds(id) VALUES (20)")
        .await
        .expect("explicit high mark");
    let error = driver
        .advance_transfer_identity_sequences(&handle, None, "bounds", &ids)
        .await
        .expect_err("no representable next identifier");
    assert!(
        matches!(error,DriverError::Unsupported(s) if s.contains("beyond the imported high-water mark"))
    );
    driver
        .rollback(tx)
        .await
        .expect("rollback rows with exhausted future IDs");
    let retained: i64 = sqlx::query_scalar(&format!("SELECT count(*) FROM {schema}.bounds"))
        .fetch_one(&mut fixture.oracle)
        .await
        .expect("source rows rolled back");
    assert_eq!(retained, 0);
    let first: i16 = sqlx::query_scalar(&format!(
        "INSERT INTO {schema}.bounds DEFAULT VALUES RETURNING id"
    ))
    .fetch_one(&mut fixture.oracle)
    .await
    .expect("independent unaffected next value");
    assert_eq!(first, 10);

    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("non-identity table transaction");
    assert!(
        matches!(driver.advance_transfer_identity_sequences(&handle,Some(&schema),"not_sequence",&ids).await,
        Err(DriverError::Unsupported(s)) if s.contains("has no owned serial/identity sequence"))
    );
    driver
        .rollback(tx)
        .await
        .expect("rollback no owned sequence");
    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("missing table transaction");
    assert!(
        matches!(driver.advance_transfer_identity_sequences(&handle,Some(&schema),"missing_fixture",&ids).await,
        Err(DriverError::QueryFailed(s)) if s.contains("cannot lock target table"))
    );
    driver.rollback(tx).await.expect("rollback failed lock");

    driver
        .execute(&handle, &format!("SET ROLE {role}"))
        .await
        .expect("isolated transfer role");
    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("role transaction without sequence read");
    assert!(
        matches!(driver.advance_transfer_identity_sequences(&handle,Some(&schema),"roles",&ids).await,
        Err(DriverError::Unsupported(s)) if s.contains("cannot read the owned sequence"))
    );
    driver
        .rollback(tx)
        .await
        .expect("manual rollback without data changes");
    sqlx::query(&format!(
        "GRANT SELECT ON SEQUENCE {schema}.roles_id_seq TO {role}"
    ))
    .execute(&mut fixture.oracle)
    .await
    .expect("role can read but does not own sequence");
    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("role transaction without sequence ownership");
    assert!(
        matches!(driver.advance_transfer_identity_sequences(&handle,Some(&schema),"roles",&ids).await,
        Err(DriverError::QueryFailed(s)) if s.contains("cannot safely lock owned sequence"))
    );
    driver
        .rollback(tx)
        .await
        .expect("rollback refused sequence ownership");
    driver
        .execute(&handle, "RESET ROLE")
        .await
        .expect("leave role");
    let (next, called): (i64, bool) = sqlx::query_as(&format!(
        "SELECT last_value,is_called FROM {schema}.roles_id_seq"
    ))
    .fetch_one(&mut fixture.oracle)
    .await
    .expect("roles cannot damage sequence");
    assert_eq!((next, called), (1, false));
    driver
        .disconnect(handle)
        .await
        .expect("retained connection cleanup");
    sqlx::raw_sql(&format!("DROP SCHEMA {schema} CASCADE; DROP ROLE {role}"))
        .execute(&mut fixture.oracle)
        .await
        .expect("remove disposable identities and role");
}

async fn backend_waits_for_lock(oracle: &mut PgConnection, pid: i32) {
    tokio::time::timeout(Duration::from_secs(5),async {
        loop {
            let waits = sqlx::query_scalar::<_,bool>(
                "SELECT EXISTS(SELECT 1 FROM pg_stat_activity WHERE pid=$1 AND wait_event_type='Lock' AND query LIKE 'ALTER SEQUENCE %')"
            ).bind(pid).fetch_one(&mut *oracle).await.expect("independent server lock oracle");
            if waits { break; }
            tokio::time::sleep(Duration::from_millis(20)).await;
        }
    }).await.expect("driver reached the sequence DDL lock while concurrent owner holds it");
}

#[tokio::test]
async fn identity_import_rechecks_real_sequence_after_a_concurrent_owner_changes_it() {
    let mut fixture = Fixture::open().await;
    let database = fixture.config.database.as_deref().expect("fixture name");
    let schema = format!("dz_ids_race_{}", uuid::Uuid::new_v4().simple());
    let relation = format!("{schema}.events");
    sqlx::raw_sql(&format!(
        "CREATE SCHEMA {schema}; CREATE TABLE {relation}(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"
    )).execute(&mut fixture.oracle).await.expect("isolated real sequence");
    let driver = Arc::new(PostgresDriver::new());
    let handle = driver
        .connect_fixed_session(&fixture.config)
        .await
        .expect("pinned import backend");
    let observed = driver
        .query(&handle, "SELECT pg_backend_pid()")
        .await
        .expect("exact live backend");
    let pid = match observed.rows[0][0] {
        Some(datazen_driver_api::Value::Integer(pid)) => i32::try_from(pid).expect("Postgres PID"),
        _ => panic!("unexpected backend pid"),
    };
    let mut concurrent = fixture.connect_to(database).await;
    sqlx::raw_sql(&format!(
        "BEGIN; ALTER SEQUENCE {schema}.events_id_seq INCREMENT BY 2"
    ))
    .execute(&mut concurrent)
    .await
    .expect("concurrent sequence option change remains uncommitted");
    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("real import transaction");
    driver
        .execute(&handle, &format!("INSERT INTO {relation} (id) VALUES (31)"))
        .await
        .expect("uncommitted explicitly imported row");
    let worker = {
        let driver = Arc::clone(&driver);
        let h = handle.clone();
        let schema = schema.clone();
        tokio::spawn(async move {
            driver
                .advance_transfer_identity_sequences(&h, Some(&schema), "events", &["id".into()])
                .await
        })
    };
    backend_waits_for_lock(&mut fixture.oracle, pid).await;
    sqlx::query("COMMIT")
        .execute(&mut concurrent)
        .await
        .expect("owner commits changed sequence contract");
    let result = tokio::time::timeout(Duration::from_secs(5), worker)
        .await
        .expect("driver released its wait")
        .expect("live worker task");
    assert!(
        matches!(result,Err(DriverError::Unsupported(s)) if s.contains("changed while transfer was preparing"))
    );
    driver
        .rollback(tx)
        .await
        .expect("rollback staged import after conflict");
    let rows: i64 = sqlx::query_scalar(&format!("SELECT count(*) FROM {relation}"))
        .fetch_one(&mut fixture.oracle)
        .await
        .expect("independent rollback readback");
    assert_eq!(rows, 0);
    let increment:i64 = sqlx::query_scalar("SELECT increment_by FROM pg_sequences WHERE schemaname=$1 AND sequencename='events_id_seq'")
        .bind(&schema).fetch_one(&mut fixture.oracle).await.expect("preserved concurrent SQL change");
    assert_eq!(increment, 2);
    driver
        .disconnect(handle)
        .await
        .expect("release import connection");
    sqlx::query(&format!("DROP SCHEMA {schema} CASCADE"))
        .execute(&mut fixture.oracle)
        .await
        .expect("remove disposable sequence");
}
