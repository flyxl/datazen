use super::Fixture;
use datazen_driver_api::{DatabaseDriver, DriverError};
use datazen_driver_postgres::PostgresDriver;

#[tokio::test]
async fn live_sequence_reseed_preserves_step_and_rolls_back_unsafe_imports() {
    let mut fixture = Fixture::open().await;
    let suffix = uuid::Uuid::new_v4().simple().to_string();
    let schema = format!("seq_{suffix}");
    let role = format!("seq_writer_{suffix}");
    let table = format!("{schema}.measurements");
    let sequence = format!("{schema}.measurements_id_seq");
    sqlx::raw_sql(&format!(
        "CREATE SCHEMA {schema};
         CREATE ROLE {role};
         CREATE TABLE {table} (id bigint GENERATED BY DEFAULT AS IDENTITY
            (START WITH 100 INCREMENT BY 7 MAXVALUE 114) PRIMARY KEY);
         GRANT USAGE ON SCHEMA {schema} TO {role};
         GRANT SELECT, INSERT, UPDATE ON {table} TO {role};"
    ))
    .execute(&mut fixture.oracle)
    .await
    .expect("create real sequence and a limited import role");
    let driver = PostgresDriver::new();
    let column = ["id".to_string()];
    let handle = driver
        .connect(&fixture.config)
        .await
        .expect("driver connection");
    assert!(matches!(
        driver
            .advance_transfer_identity_sequences(&handle, Some(&schema), "measurements", &column)
            .await,
        Err(DriverError::TransactionError(_))
    ));

    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("first import");
    driver
        .execute(&handle, &format!("INSERT INTO {table} (id) VALUES (23)"))
        .await
        .expect("import below start");
    driver
        .advance_transfer_identity_sequences(
            &handle,
            Some(&schema),
            "measurements",
            &["id".into(), "id".into()],
        )
        .await
        .expect("deduplicate repeated column and preserve sequence start");
    driver.commit(tx).await.expect("commit first import");
    let generated =
        sqlx::query_scalar::<_, i64>(&format!("INSERT INTO {table} DEFAULT VALUES RETURNING id"))
            .fetch_one(&mut fixture.oracle)
            .await
            .expect("independent PostgreSQL allocates original start");
    assert_eq!(generated, 100);

    let tx = driver
        .begin_transaction(&handle)
        .await
        .expect("bounded import");
    driver
        .execute(&handle, &format!("INSERT INTO {table} (id) VALUES (114)"))
        .await
        .expect("explicit ID at maximum");
    let error = driver
        .advance_transfer_identity_sequences(&handle, Some(&schema), "measurements", &column)
        .await
        .expect_err("no unused generated ID after upper bound");
    assert!(
        matches!(error, DriverError::Unsupported(message) if message.contains("configured bounds"))
    );
    driver.rollback(tx).await.expect("failed import rolls back");

    for grant_sequence_read in [false, true] {
        if grant_sequence_read {
            sqlx::query(&format!("GRANT SELECT ON SEQUENCE {sequence} TO {role}"))
                .execute(&mut fixture.oracle)
                .await
                .expect("grant read but not alter ownership");
        }
        let tx = driver
            .begin_transaction(&handle)
            .await
            .expect("limited-role import");
        driver
            .execute(&handle, &format!("SET LOCAL ROLE {role}"))
            .await
            .expect("apply actual PostgreSQL role");
        driver
            .execute(&handle, &format!("INSERT INTO {table} (id) VALUES (110)"))
            .await
            .expect("role may import explicit ID");
        let error = driver
            .advance_transfer_identity_sequences(&handle, Some(&schema), "measurements", &column)
            .await
            .expect_err("sequence privileges prevent unsafe import");
        if grant_sequence_read {
            assert!(
                matches!(error, DriverError::QueryFailed(message) if message.contains("check sequence ownership"))
            );
        } else {
            assert!(
                matches!(error, DriverError::Unsupported(message) if message.contains("grant sequence SELECT and ownership"))
            );
        }
        driver
            .rollback(tx)
            .await
            .expect("failed limited-role import rolls back");
    }
    let remaining = sqlx::query_scalar::<_, i64>(&format!("SELECT id FROM {table} ORDER BY id"))
        .fetch_all(&mut fixture.oracle)
        .await
        .expect("verify committed PostgreSQL rows");
    assert_eq!(remaining, [23, 100]);
    let next =
        sqlx::query_scalar::<_, i64>(&format!("INSERT INTO {table} DEFAULT VALUES RETURNING id"))
            .fetch_one(&mut fixture.oracle)
            .await
            .expect("failed imports never changed next ID");
    assert_eq!(next, 107);
    driver
        .disconnect(handle)
        .await
        .expect("disconnect after import");
}
