#!/usr/bin/env node
/**
 * Generate src/locales/builtinLocales.ts from the built-in locale manifest.
 *
 * Single source of truth for the app's built-in UI languages is
 * src/locales/builtin-locales.json (list of { code, label }).
 * This script regenerates the git-ignored `builtinLocales.ts` that
 * src/locales/index.ts re-exports, so `BUILTIN_LOCALES` / `builtinLocales`
 * always reflect exactly the manifest. Settings reads the same keys so the
 * language dropdown matches.
 *
 * Usage:
 *   node scripts/generate-builtin-locales.mjs                    # (re)generate from manifest
 *   node scripts/generate-builtin-locales.mjs list            # print built-in locales
 *   node scripts/generate-builtin-locales.mjs add <code> [label]  # add a language + regenerate
 *   node scripts/generate-builtin-locales.mjs remove <code>       # remove a language + regenerate
 *
 * Wired in as `pnpm locales:*` and run automatically on prepare / pretest.
 * Labels fall back to the endonym table below when not supplied.
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const MANIFEST = resolve(ROOT, 'src/locales/builtin-locales.json');
const OUT = resolve(ROOT, 'src/locales/builtinLocales.ts');

/** Canonical endonym names per locale code (used when `add` omits a label). */
const ENDONYMS = {
  en: 'English',
  'zh-CN': '简体中文',
  'zh-TW': '繁體中文',
  es: 'Español',
  fr: 'Français',
  de: 'Deutsch',
  ja: '日本語',
  'pt-BR': 'Português (Brasil)',
  ru: 'Русский',
  ko: '한국어',
};

function readManifest() {
  let raw;
  try {
    raw = JSON.parse(readFileSync(MANIFEST, 'utf-8'));
  } catch {
    return [];
  }
  const entries = Array.isArray(raw?.locales) ? raw.locales : [];
  return entries
    .filter((e) => typeof e?.code === 'string' && e.code)
    .map((e) => ({
      code: e.code,
      label:
        typeof e.label === 'string' && e.label ? e.label : (ENDONYMS[e.code] ?? e.code),
    }));
}

function writeManifest(entries) {
  const json = `${JSON.stringify({ locales: entries }, null, 2)}\n`;
  writeFileSync(MANIFEST, json, 'utf-8');
}

function hasLocaleFile(code) {
  return existsSync(resolve(ROOT, `src/locales/${code}.ts`));
}

/** locale code → valid TS identifier for the default-import binding (zh-CN -> zhCN). */
function bindingName(code) {
  const name = code.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  return name || `l_${code}`;
}

function buildTs(entries) {
  const imports = entries
    .map(({ code }) => `import ${bindingName(code)} from './${code}';`)
    .join('\n');
  const arrayLiteral = entries.map(({ code }) => `'${code}'`).join(', ');
  const dictLines = entries
    .map(({ code }) => `  '${code}': ${bindingName(code)},`)
    .join('\n');
  const labelLines = entries
    .map(({ code, label }) => `  '${code}': ${JSON.stringify(label)},`)
    .join('\n');

  const ts = `// AUTO-GENERATED by scripts/generate-builtin-locales.mjs — do not edit by hand.
// Source of truth: src/locales/builtin-locales.json.
// Regenerate with \`pnpm locales:generate\` (or prepare / pretest hooks).
import type { TranslationKey } from './zh-CN';
${imports}

export const BUILTIN_LOCALES = [${arrayLiteral}] as const;

export type BuiltinLocale = (typeof BUILTIN_LOCALES)[number];

export const builtinLocales: Record<BuiltinLocale, Record<TranslationKey, string>> = {
${dictLines}
};

/** Endonym display label per built-in locale (used by the settings dropdown). */
export const BUILTIN_LOCALE_LABELS: Record<BuiltinLocale, string> = {
${labelLines}
};
`;
  return `${ts.trimEnd()}\n`;
}

function regenerate(entries) {
  writeFileSync(OUT, buildTs(entries), 'utf-8');
  console.log(
    `[generate-builtin-locales] wrote ${OUT} (${entries.map((e) => e.code).join(', ')})`,
  );
}

const [, , sub = 'generate', ...args] = process.argv;

if (sub === 'list') {
  for (const { code, label } of readManifest()) console.log(`${code}\t${label}`);
  process.exit(0);
}

if (sub === 'add') {
  if (args.length === 0) {
    console.error('[generate-builtin-locales] usage: add <code> [label]');
    process.exit(1);
  }
  const entries = readManifest();
  for (const arg of args) {
    const [codeRaw = '', ...labelRest] = arg.split('=');
    const code = codeRaw.trim();
    if (!code) continue;
    if (!hasLocaleFile(code)) {
      console.error(
        `[generate-builtin-locales] no locale pack src/locales/${code}.ts — add the translations first`,
      );
      process.exit(1);
    }
    if (entries.some((e) => e.code === code)) {
      console.error(`[generate-builtin-locales] ${code} is already built-in`);
      process.exit(1);
    }
    const label = (labelRest.join('=') || ENDONYMS[code] || code).trim();
    entries.push({ code, label });
  }
  writeManifest(entries);
  regenerate(entries);
  process.exit(0);
}

if (sub === 'remove') {
  if (args.length === 0) {
    console.error('[generate-builtin-locales] usage: remove <code>');
    process.exit(1);
  }
  const entries = readManifest().filter((e) => !args.includes(e.code));
  writeManifest(entries);
  regenerate(entries);
  process.exit(0);
}

// default: (re)generate from manifest
regenerate(readManifest());