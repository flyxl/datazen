const OFFSET_INTERIOR = -1;
function coordinates(source) {
  const bounds=[0];
  let bytes=0;
  for(let i=0;i<source.length;) {
    const at=source.codePointAt(i), s=String.fromCodePoint(at);
    i+=s.length;
    if(s==='\r' && source[i]==='\n'){i++;bytes++;}
    bytes+=Buffer.byteLength(s);
    if(s.length===2)bounds.push(OFFSET_INTERIOR);
    bounds.push(bytes);
  }
  const interval = (m)=> m ? [bounds[m.from],bounds[m.to]] : null;
  return {bounds,interval};
}
