// Independent differential for the indexed Rust cluster strategy: compare
// before/after at every UTF-16 offset, including physically split astrals.
function indexedBreaks(window) {
  const result=[0];
  const zwj=0x200d;
  const flag=c=>c>=0x1f1e6&&c<=0x1f1ff;
  let at=0,prior=0,odd=false;
  for(const char of window) {
    const cp=char.codePointAt(0);
    if(at>0&&prior!==zwj&&cp!==zwj&&!isExtendingChar(cp)&&!(flag(cp)&&odd))result.push(at);
    odd=flag(cp)&&(!flag(prior)||!odd);
    prior=cp;at+=char.length;
  }
  if(at>0)result.push(at);
  return result;
}
